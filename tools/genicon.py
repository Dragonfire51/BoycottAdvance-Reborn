#!/usr/bin/env python3
# Regenerates src/icon.h (embedded window icon) and assets/icon.ico
# (Windows executable icon). 32x32 ARGB, GBA-themed, drawn procedurally.
import os, struct

W = H = 32
CLEAR   = (0, 0, 0, 0)
BODY    = (108, 92, 168, 255)
BODY_HI = (140, 124, 200, 255)
BODY_LO = (74, 62, 120, 255)
SCREEN  = (34, 40, 60, 255)
SCREEN2 = (86, 190, 120, 255)
GROUND  = (60, 150, 90, 255)
DPAD    = (60, 54, 78, 255)
BTN_A   = (208, 70, 90, 255)
BTN_B   = (70, 110, 200, 255)

px = [[CLEAR for _ in range(W)] for _ in range(H)]
def rect(x0, y0, x1, y1, c):
    for y in range(max(0, y0), min(H, y1 + 1)):
        for x in range(max(0, x0), min(W, x1 + 1)):
            px[y][x] = c

rect(4, 3, 27, 28, BODY)
for (x, y) in [(4, 3), (27, 3), (4, 28), (27, 28)]:
    px[y][x] = CLEAR
rect(5, 3, 26, 4, BODY_HI)
rect(5, 27, 26, 28, BODY_LO)
rect(7, 6, 24, 15, SCREEN)
rect(9, 8, 22, 13, SCREEN2)
rect(9, 11, 22, 13, GROUND)
rect(8, 19, 11, 22, DPAD)
rect(6, 20, 13, 21, DPAD)
rect(22, 18, 24, 20, BTN_A)
rect(18, 21, 20, 23, BTN_B)
rect(5, 5, 6, 9, BODY_LO)
rect(25, 5, 26, 9, BODY_LO)

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(root, 'src', 'icon.h'), 'w') as f:
    f.write('/* Generated by tools/genicon.py: 32x32 ARGB8888 window icon. */\n')
    f.write('#ifndef GBA_ICON_DATA_H\n#define GBA_ICON_DATA_H\n#include <stdint.h>\n')
    f.write('#define GBA_ICON_W 32\n#define GBA_ICON_H 32\n')
    f.write('static const uint32_t gba_icon_argb[GBA_ICON_W*GBA_ICON_H] = {\n')
    for y in range(H):
        row = ['0x%08X' % ((a << 24) | (r << 16) | (g << 8) | b)
               for (r, g, b, a) in px[y]]
        f.write('  ' + ','.join(row) + ',\n')
    f.write('};\n#endif\n')

# --- .ico (32bpp BGRA, bottom-up) ---
xor = bytearray()
for y in range(H - 1, -1, -1):
    for x in range(W):
        r, g, b, a = px[y][x]
        xor += bytes((b, g, r, a))
and_mask = bytearray(((W + 31) // 32) * 4 * H)     # 1bpp mask, all zero
dib = struct.pack('<IiiHHIIiiII', 40, W, H * 2, 1, 32, 0, len(xor) + len(and_mask),
                  0, 0, 0, 0) + xor + and_mask
ico = struct.pack('<HHH', 0, 1, 1)
ico += struct.pack('<BBBBHHII', W, H, 0, 0, 1, 32, len(dib), 22) + dib
os.makedirs(os.path.join(root, 'assets'), exist_ok=True)
with open(os.path.join(root, 'assets', 'icon.ico'), 'wb') as f:
    f.write(ico)
print('wrote src/icon.h and assets/icon.ico')
